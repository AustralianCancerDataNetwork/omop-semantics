#!/usr/bin/env python3
"""Generate the statically typed tree for the bundled default runtime."""

from __future__ import annotations

import argparse
import keyword
import re
import sys
from pathlib import Path

from linkml_runtime.loaders import yaml_loader

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from omop_semantics import INSTANCE_DIR  # noqa: E402
from omop_semantics.runtime.value_sets import (  # noqa: E402
    RuntimeEnum,
    RuntimeGroup,
    RuntimeSemanticUnit,
    RuntimeValueSet,
    RuntimeValueSets,
    compile_valuesets,
    index_semantic_units,
    interpolate_valuesets,
)
from omop_semantics.schema.generated_models.omop_named_sets import (  # noqa: E402
    CDMSemanticUnits,
    OmopConcept,
)

OUTPUT = SRC / "omop_semantics/runtime/default_valuesets.pyi"


def _identifier(value: str) -> str:
    result = re.sub(r"\W", "_", value)
    if not result or result[0].isdigit():
        result = f"_{result}"
    if keyword.iskeyword(result):
        result += "_"
    return result


def _load_runtime() -> RuntimeValueSets:
    """Load the shipped YAML through the same compiler as the runtime module."""
    enumerator_instances = INSTANCE_DIR / "enumerators.yaml"
    valueset_definitions = INSTANCE_DIR / "valuesets.yaml"
    enumerators = yaml_loader.load(
        str(enumerator_instances), target_class=CDMSemanticUnits
    )
    idx = index_semantic_units(enumerators)
    raw_valuesets = yaml_loader.load_as_dict(str(valueset_definitions))
    value_set_objects = interpolate_valuesets(raw_valuesets, idx)
    compiled = compile_valuesets(value_set_objects)
    return compiled


def _class_name(prefix: str, *parts: str) -> str:
    suffix = "_".join(_identifier(part) for part in parts)
    return f"_{prefix}_{suffix}"


def _is_flattened_label(label: str) -> bool:
    """Whether the runtime can actually expose this label via dot lookup."""
    return (
        label.isidentifier()
        and not label.startswith("_")
        and not hasattr(RuntimeSemanticUnit, label)
        and not hasattr(RuntimeEnum, label)
        and not hasattr(RuntimeGroup, label)
    )


def _unit_member_types(unit: RuntimeSemanticUnit) -> dict[str, type[object]]:
    """Return accessible unit attributes and the values they resolve to."""
    members: dict[str, type[object]] = {}
    for enum in unit.enums.values():
        members.update(
            {label: int for label in enum.labels if _is_flattened_label(label)}
        )
    for group in unit.groups.values():
        members.update(
            {label: int for label in group.labels if _is_flattened_label(label)}
        )
    members.update({name: OmopConcept for name in unit.concepts})
    members.update({name: RuntimeEnum for name in unit.enums})
    members.update(
        {
            name: int if group.is_singleton else RuntimeGroup
            for name, group in unit.groups.items()
        }
    )
    return members


def render_stub() -> str:
    """Return a stub matching the actual attribute access behavior."""
    compiled = _load_runtime()
    has_named_concepts = any(
        unit.concepts
        for value_set in compiled._valuesets.values()
        for unit in value_set.members.values()
    )
    lines = [
        "\"\"\"Generated by scripts/generate_runtime_stubs.py; do not edit.\"\"\"",
        "from pathlib import Path",
        "from omop_semantics.runtime.value_sets import (",
        "    RuntimeEnum,",
        "    RuntimeGroup,",
        "    RuntimeSemanticUnit,",
        "    RuntimeValueSet,",
        "    RuntimeValueSets,",
        ")",
        "from omop_semantics.schema.generated_models.omop_named_sets import (",
        "    CDMValueSets,",
        "    CDMSemanticUnits,",
        "    OmopSemanticObject,",
        ")",
        "",
    ]
    if has_named_concepts:
        lines.insert(lines.index("    OmopSemanticObject,"), "    OmopConcept,")

    value_set_classes: dict[str, str] = {}
    unit_classes: dict[tuple[str, str], str] = {}
    for set_name, value_set in compiled._valuesets.items():
        set_class = _class_name("RuntimeValueSet", set_name)
        value_set_classes[set_name] = set_class
        lines.append(f"class {set_class}(RuntimeValueSet):")
        for unit_name, unit in value_set.members.items():
            unit_class = _class_name("RuntimeSemanticUnit", set_name, unit_name)
            unit_classes[(set_name, unit_name)] = unit_class
            lines.append(f"    {unit_name}: {unit_class}")
        if not value_set.members:
            lines.append("    ...")
        lines.append("")

        for unit_name, unit in value_set.members.items():
            unit_class = unit_classes[(set_name, unit_name)]
            lines.append(f"class {unit_class}(RuntimeSemanticUnit):")
            members = _unit_member_types(unit)
            for label, member_type in sorted(members.items()):
                lines.append(f"    {label}: {member_type.__name__}")
            if not members:
                lines.append("    ...")
            lines.append("")

    lines.append("class _DefaultRuntime(RuntimeValueSets):")
    for set_name, class_name in value_set_classes.items():
        lines.append(f"    {set_name}: {class_name}")
    if not value_set_classes:
        lines.append("    ...")

    lines.extend(
        [
            "",
            "schema_path: Path",
            "enumerator_instances: Path",
            "valueset_definitions: Path",
            "enumerators: CDMSemanticUnits",
            "idx: dict[str, OmopSemanticObject]",
            "value_sets: dict[str, object]",
            "value_set_objects: CDMValueSets",
            "runtime: _DefaultRuntime",
            "",
        ]
    )
    return "\n".join(lines)


def runtime_paths() -> list[tuple[tuple[str, ...], type[object]]]:
    """Return every attribute/type pair declared by the generated class tree."""
    compiled = _load_runtime()
    result: list[tuple[tuple[str, ...], type[object]]] = []
    for set_name, value_set in compiled._valuesets.items():
        result.append(((set_name,), RuntimeValueSet))
        for unit_name, unit in value_set.members.items():
            result.append(((set_name, unit_name), RuntimeSemanticUnit))
            result.extend(
                ((set_name, unit_name, name), member_type)
                for name, member_type in _unit_member_types(unit).items()
            )
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the checked-in stub differs from the generated content",
    )
    args = parser.parse_args()
    generated = render_stub()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run: uv run python scripts/generate_runtime_stubs.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(generated)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
